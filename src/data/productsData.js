export const getProductById = (id) => {
  if (!id) return PRODUCTS[0];
  const strId = String(id).toLowerCase().trim();
  const numMatches = strId.match(/\d+/);
  const numId = numMatches ? parseInt(numMatches[0], 10) : null;
  const standardAmbId = numId !== null ? `amb-${String(numId).padStart(2, '0')}` : '';

  return PRODUCTS.find(p => 
    p.id.toLowerCase() === strId || 
    p.id.toLowerCase() === standardAmbId ||
    (numId !== null && p.index === numId) ||
    p.sku.toLowerCase() === strId
  ) || PRODUCTS[0];
};
